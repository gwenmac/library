GRANT ALL PRIVILEGES ON *.* TO 'orangutan'@'%' WITH GRANT OPTION;
FLUSH PRIVILEGES;

SET NAMES 'utf8mb4';

CREATE DATABASE library;

USE library;

-- Households (must come first — other tables reference this)

CREATE TABLE households (
    id         BIGINT NOT NULL AUTO_INCREMENT,
    name       VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id)
);

-- Users (must come second — other tables reference this)

CREATE TABLE users (
    id            BIGINT NOT NULL AUTO_INCREMENT,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          ENUM('admin', 'user') NOT NULL DEFAULT 'user',
    household_id  BIGINT NOT NULL,
    created_at    DATETIME NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (household_id) REFERENCES households(id)
);

-- Lookup tables (no dependencies)

CREATE TABLE genres (
    id   BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE tags (
    id   BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE statuses (
    id   BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE languages (
    id   BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL UNIQUE,
    code VARCHAR(10)  NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE editions (
    id   BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

-- Authors (depends on household)

CREATE TABLE authors (
     id           BIGINT NOT NULL AUTO_INCREMENT,
     first_name   VARCHAR(255),
     last_name    VARCHAR(255) NOT NULL,
     household_id BIGINT NOT NULL,
     PRIMARY KEY (id),
     UNIQUE KEY (household_id, last_name, first_name),
     FOREIGN KEY (household_id) REFERENCES households(id)
);

-- Series (depends on household)

CREATE TABLE series (
    id           BIGINT NOT NULL AUTO_INCREMENT,
    name         VARCHAR(255) NOT NULL,
    status       VARCHAR(50) NOT NULL DEFAULT 'NOT_STARTED',
    household_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY (household_id, name),
    FOREIGN KEY (household_id) REFERENCES households(id)
);

-- Books (depends on series, household)

CREATE TABLE books (
   id           BIGINT NOT NULL AUTO_INCREMENT,
   title        VARCHAR(255) NOT NULL,
   description  TEXT,
   page_count   INT,
   year         INT,
   sort_title   VARCHAR(255),
   series_id    BIGINT,
   series_order INT,
   edition_id   BIGINT,
   household_id BIGINT NOT NULL,
   created_at   DATETIME,
   updated_at   DATETIME,
   PRIMARY KEY (id),
   FOREIGN KEY (series_id)    REFERENCES series(id),
   FOREIGN KEY (edition_id)   REFERENCES editions(id),
   FOREIGN KEY (household_id) REFERENCES households(id)
);

-- Book status (depends on books, statuses)

CREATE TABLE book_status (
    id         BIGINT NOT NULL AUTO_INCREMENT,
    book_id    BIGINT NOT NULL,
    status_id  BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    started_at DATE,
    finished_at DATE,
    updated_at DATETIME,
    PRIMARY KEY (id),
    UNIQUE KEY (book_id, user_id),
    FOREIGN KEY (book_id)   REFERENCES books(id),
    FOREIGN KEY (status_id) REFERENCES statuses(id),
    FOREIGN KEY (user_id)   REFERENCES users(id)
);

-- Reviews (depends on books, users)

CREATE TABLE reviews (
    id         BIGINT NOT NULL AUTO_INCREMENT,
    book_id    BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    rating     SMALLINT CHECK (rating BETWEEN 1 AND 5),
    notes      TEXT,
    created_at DATETIME,
    PRIMARY KEY (id),
    UNIQUE KEY (book_id, user_id),
    FOREIGN KEY (book_id) REFERENCES books(id),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

-- ManyToMany join tables generated by @JoinTable on Book

CREATE TABLE book_genres (
    book_id  BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,
    PRIMARY KEY (book_id, genre_id),
    FOREIGN KEY (book_id)  REFERENCES books(id),
    FOREIGN KEY (genre_id) REFERENCES genres(id)
);

CREATE TABLE book_tags (
     book_id  BIGINT NOT NULL,
     tag_id BIGINT NOT NULL,
     PRIMARY KEY (book_id, tag_id),
     FOREIGN KEY (book_id)  REFERENCES books(id),
     FOREIGN KEY (tag_id) REFERENCES tags(id)
);

CREATE TABLE book_languages (
    book_id     BIGINT NOT NULL,
    language_id BIGINT NOT NULL,
    PRIMARY KEY (book_id, language_id),
    FOREIGN KEY (book_id)     REFERENCES books(id),
    FOREIGN KEY (language_id) REFERENCES languages(id)
);

CREATE TABLE book_authors (
    book_id   BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    PRIMARY KEY (book_id, author_id),
    FOREIGN KEY (book_id)   REFERENCES books(id),
    FOREIGN KEY (author_id) REFERENCES authors(id)
);


-- Gauges

CREATE TABLE gauges (
    id          BIGINT NOT NULL AUTO_INCREMENT,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    user_id     BIGINT NOT NULL,
    created_at  DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY (user_id, name),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE gauge_entries (
    id         BIGINT NOT NULL AUTO_INCREMENT,
    gauge_id   BIGINT NOT NULL,
    delta      INT NOT NULL,
    note       VARCHAR(255),
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (gauge_id) REFERENCES gauges(id) ON DELETE CASCADE
);

